/** 构造一个检查型测试点。expected 是给学员看的要求说明；stdin 存放规则 JSON */
function C(name: string, rule: PromptRule, expected: string, hidden = false): TestCase {
  return { name, stdin: JSON.stringify({ rule, hint: name }), expected, hidden };
}

/** 由测试点生成 Level.runtime：可见检查项，供「运行」按钮输出体检报告 */
function RT(tests: TestCase[]): string {
  return JSON.stringify({
    checks: tests.filter((t) => !t.hidden).map((t) => JSON.parse(t.stdin) as { rule: PromptRule; hint: string }),
  });
}

